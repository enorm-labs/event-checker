// Build docs/ops/dashboard/dashboard.css from the classes the page uses.
//
// The operations page is a static file opened from file://, so Tailwind cannot run at request time
// and a CDN <script> would leave the page unstyled without a network. This compiles once, with the
// tailwindcss pinned in package.json, and the result is committed; scripts/dashboard-parity.sh
// fails when the committed file is not what this produces.
//
// Run from events-frontend/, where node_modules is:   node scripts/ops-page-css.mjs
//
// @tailwindcss/node and @tailwindcss/oxide are what @tailwindcss/vite is built on and ship beside
// it at the same version, so no new dependency is needed for a page that has no Vite build.

import { compile } from '@tailwindcss/node'
import { Scanner } from '@tailwindcss/oxide'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pageDir = resolve(here, '../../docs/ops/dashboard')
const out = resolve(pageDir, 'dashboard.css')

const compiler = await compile('@import "tailwindcss";', {
  base: resolve(here, '..'),
  onDependency() {},
})
const scanner = new Scanner({
  sources: [{ base: pageDir, pattern: '{index.html,dashboard.js}', negated: false }],
})
const candidates = scanner.scan()
const css = compiler.build(candidates)

const header = `/* Generated by events-frontend/scripts/ops-page-css.mjs from index.html and dashboard.js. Do not edit. */\n`
const next = header + css
let previous = ''
try {
  previous = readFileSync(out, 'utf8')
} catch {
  // first build
}
if (previous !== next) writeFileSync(out, next)
console.log(
  `${out}: ${candidates.length} classes, ${next.length} bytes${previous === next ? ', unchanged' : ''}`,
)
